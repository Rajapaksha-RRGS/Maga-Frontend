// Helper to get unique source projects across a list
export function getUniqueSourceProjects(items: { sourceProject?: string; currentWorkingProject?: string }[]): string[] {
  return Array.from(new Set(items.map((i) => i.sourceProject || i.currentWorkingProject || ''))).filter(Boolean).sort();
}

// Helper to get unique categories/trade groups
export function getUniqueCategories(items: { type?: string; tradeGroup?: string; activityType?: string }[]): string[] {
  return Array.from(
    new Set(items.map((i) => i.type || i.tradeGroup || i.activityType || '').filter(Boolean))
  ).sort();
}

