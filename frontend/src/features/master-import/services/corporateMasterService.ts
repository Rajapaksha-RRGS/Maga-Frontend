/**
 * corporateMasterService.ts
 *
 * Central Corporate ERP Master Data Repository (IFS / SAP / Central Database).
 * Provides verified master data records across all company projects & central depots.
 * Project sites / tenants import master records from this central catalog instead
 * of typing ad-hoc manual records.
 */

export interface CorporateEquipment {
  code: string;
  name: string; // Description
  searchKey?: string;
  costRate?: number;
  currency?: string;
  type: string;
  model: string;
  registrationNo: string;
  capacity: string;
  sourceProject: string;
  status: 'active';
}

export interface CorporateBusinessPartner {
  code: string;
  name: string;
  type: string;
  contactPerson: string;
  phone: string;
  email: string;
  address: string;
  sourceProject: string;
  rating: string;
}

export interface CorporateEmployee {
  employeeCode: string;
  callingName: string;
  fullName: string;
  nicNo: string;
  tradeGroup: string;
  isOperator?: boolean;
  licenseNo?: string;
  businessPartnerCode?: string; // e.g. "BP1004093" (Number/Code)
  businessPartnerName?: string; // e.g. "Aruna Builders (Pvt) Ltd"
  businessPartner?: string; // Backwards compatibility for UI
  currentWorkingProject?: string;
  sourceProject?: string;
  epfNo?: string;
  dailyRate?: number;
  skillLevel?: string;
}

export interface CorporateActivityCode {
  code: string;
  description: string;
  searchKey?: string;
  activityType?: string; // 'Work Package' | 'WBS Element' | 'Control Account' | 'Planning Package' | 'Milestone'
  unit?: string;
  timeUnit?: string;
  currentWorkingProject?: string;
  sourceProject?: string;
  tradeGroup?: string;
}

export interface CorporateProject {
  projectCode: string;
  description: string;
  searchKey: string;
  projectManager?: string;
  status: 'Active' | 'Closed' | 'Suspended';
  addressCode?: string;
  projectName?: string;
  enterpriseUnit?: string; // 'BDG001' | 'RDS001' | 'BRG001' | 'WRK001'
  divisionType?: string;
  currency?: string;
}

